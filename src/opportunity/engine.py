    def get_opportunity_by_id(self, opportunity_id: str, topic: Optional[str] = None) -> Optional[SaaSSolutionOpportunity]:
        """Lookup an opportunity by its ID."""
        matrix = self.discover_opportunities(topic=topic or "Enterprise AI Operating Model Redesign")
        for opp in matrix.solution_opportunities:
            if opp.opportunity_id == opportunity_id:
                return opp
        return None

    def get_validation_report(self, opportunity_id: str, topic: Optional[str] = None) -> Optional[OpportunityValidationReport]:
        """Retrieve adversarial validation report for an opportunity."""
        opp = self.get_opportunity_by_id(opportunity_id, topic=topic)
        if opp:
            return opp.validation_report
        return None

    def get_solution_blueprint(self, opportunity_id: str, topic: Optional[str] = None) -> Optional[SolutionBlueprint]:
        """Retrieve complete architectural solution blueprint for an opportunity."""
        opp = self.get_opportunity_by_id(opportunity_id, topic=topic)
        if opp:
            return opp.blueprint
        return None

    def _adversarial_validation(self, opp: SaaSSolutionOpportunity, claims: Optional[List[ExtractedClaim]] = None) -> OpportunityValidationReport:
        """Adversarially challenge and validate an opportunity."""
        self._enrich_opportunity(opp, claims)
        return opp.validation_report

    def _generate_solution_blueprint(self, opp: SaaSSolutionOpportunity, claims: Optional[List[ExtractedClaim]] = None) -> SolutionBlueprint:
        """Generate architectural blueprint for an opportunity."""
        self._enrich_opportunity(opp, claims)
        return opp.blueprint

