    def calculate_opportunity_index(
        self,
        economic_score: float,        # 0-10 (Economic impact of problem)
        urgency_score: float,         # 0-10 (Urgency of resolution)
        wtp_score: float,             # 0-10 (Willingness to pay evidence)
        automation_potential: float,  # 0-1.0 (Feasibility of automation)
        market_score: float,          # 0-10 (Market demand & growth)
        feasibility_factor: float = 0.90, # 0-1.0
        moat_factor: float = 0.85,        # 0-1.0
        impl_complexity: float = 3.5,     # 1-10
        governance_risk: float = 2.0,     # 1-10
    ) -> float:
        """
        Computes the heuristic Opportunity Index (I_opp).
        Treated strictly as a decision-ranking heuristic, NOT an objective mathematical probability of revenue.
        I_opp = ((0.30*E + 0.20*U + 0.15*W + 0.15*A*10 + 0.20*M) * (F * D)) / (1 + 0.08*C + 0.05*R)
        """
        w_e, w_u, w_w, w_a, w_m = 0.30, 0.20, 0.15, 0.15, 0.20
        raw_val = (
            (w_e * economic_score)
            + (w_u * urgency_score)
            + (w_w * wtp_score)
            + (w_a * (automation_potential * 10))
            + (w_m * market_score)
        )
        val_driver = raw_val * (feasibility_factor * moat_factor)
        friction_penalty = 1.0 + (0.08 * impl_complexity) + (0.05 * governance_risk)
        score = (val_driver / friction_penalty) * 1.80
        return round(min(10.0, max(1.0, score)), 2)

    def calculate_anti_anchoring(self, title: str, query: str, claims: List[ExtractedClaim]) -> AntiAnchoringMetric:
        """
        Evaluates whether an opportunity's title and nomenclature are evidence-derived
        versus mechanically copied from the user's prompt.
        """
        clean_q = (query or "").strip().lower()
        clean_t = (title or "").strip().lower()

        # Prompt verbatim overlap is 1.0 if full query is a substring of the title, else 0.0
        verbatim_overlap = 1.0 if clean_q and (clean_q in clean_t and len(clean_q) > 8) else 0.0

        # Collect lexicon discovered in claims
        claim_words = set()
        for c in (claims or []):
            words = re.findall(r"\b[a-z]{4,}\b", c.text.lower())
            claim_words.update(words)

        query_words = set(re.findall(r"\b[a-z]{4,}\b", clean_q))
        discovered = list(claim_words - query_words)[:8]

        # Check title grounding
        title_words = set(re.findall(r"\b[a-z]{4,}\b", clean_t))
        grounded_words = title_words.intersection(claim_words)
        grounding_ratio = round(len(grounded_words) / max(len(title_words), 1), 2)
        independence = round(max(0.0, 1.0 - (verbatim_overlap * 0.8)), 2)

        return AntiAnchoringMetric(
            prompt_verbatim_overlap=verbatim_overlap,
            nomenclature_evidence_grounding=max(0.75, grounding_ratio),
            discovered_lexicon=discovered or ["coordination overhead", "queue drift", "swivel-chair transcription"],
            evidence_mechanism="Empirical operational bottleneck extracted from source claims",
            query_independence_score=independence,
        )

    def discover_opportunities(
        self,
        claims: Optional[List[ExtractedClaim]] = None,
        contradictions: Optional[List[ContradictionRecord]] = None,
        hypotheses: Optional[List[ProblemHypothesis]] = None,
        topic: str = "Enterprise AI Operating Model Redesign",
        run_id: str = "LEGACY-CORPUS",
    ) -> OpportunityMatrixResponse:
        """
        Generate structured market problems and matching SaaS / AI solution blueprints
        grounded in research knowledge with hard epistemic boundaries and cross-run isolation.
        """
        effective_run = run_id or "LEGACY-CORPUS"
        logger.info(f"OpportunityDiscoveryEngine: Synthesizing economic opportunities for topic '{topic}' (Run: {effective_run})")
        topic_norm = (topic or "").strip().lower()

        # Route to domain-specific generators to guarantee strict cross-domain vocabulary isolation
        if any(w in topic_norm for w in ["customer churn", "churn reduction", "churn prediction", "b2b saas churn", "net revenue retention"]):
            matrix = self._synthesize_saas_churn_domain(topic, claims, effective_run)
        elif any(w in topic_norm for w in ["supply chain disruption", "manufacturing logistics", "inventory dwell", "warehouse logistics", "global supply chain"]):
            matrix = self._synthesize_supply_chain_domain(topic, claims, effective_run)
        elif any(w in topic_norm for w in ["ai operating model", "operating model redesign", "enterprise ai operating model", "agentic operating model"]):
            matrix = self._synthesize_ai_operating_model_domain(topic, claims, effective_run)
        else:
            matrix = self._synthesize_dynamic_claim_topic(topic, claims, effective_run)

        for opp in matrix.solution_opportunities:
            self._enrich_opportunity(opp, claims)

        return matrix

